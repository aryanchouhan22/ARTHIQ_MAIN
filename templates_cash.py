KEYS = set(TC["hi-IN"])
for _lang, _d in TC.items():
    assert set(_d) == KEYS, f"template keys mismatch in {_lang}: {set(_d) ^ KEYS}"


def tl(lang: str) -> str:
    return lang if lang in TC else "hi-IN"


def tc(lang: str, key: str, **kw) -> str:
    return TC[tl(lang)][key].format(**kw)


def num(x) -> str:
    x = float(x)
    return str(int(x)) if x.is_integer() else f"{x:.1f}"